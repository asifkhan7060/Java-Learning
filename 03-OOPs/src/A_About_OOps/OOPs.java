package A_About_OOps;

/**

 * ====================================================<br>
 *         INTRODUCTION TO OOPs<br>
 * ====================================================<br><br>
 *
 * Before understanding Object Oriented Programming (OOP),
 * it is important to understand how programming evolved
 * over time.<br><br>
 *
 * Programming mainly evolved through three major approaches:<br><br>
 *
 * 1. Procedural Programming<br>
 * 2. Functional Programming<br>
 * 3. Object Oriented Programming (OOP)<br><br>
 *
 * ====================================================<br><br>
 * Procedural      Functional       Object Oriented
 * Programming     Programming      Programming
 * </pre><br>
 *
 * ====================================================<br><br>
 *
 * 🔹 1. Procedural Programming<br><br>
 *
 * Procedural Programming is a programming paradigm where
 * a program is divided into a collection of procedures
 * or functions.<br><br>
 *
 * The main focus is on:
 * "How a task is performed step-by-step."<br><br>
 *
 * A large problem is broken into smaller functions,
 * and these functions are executed in sequence.<br><br>
 *
 * Examples:<br>
 * • C Programming Language<br>
 * • Early BASIC Programs<br><br>
 *
 * Real-Life Example:<br><br>
 *
 * Making Tea:<br><br>
 *
 * Step 1 → Boil Water<br>
 * Step 2 → Add Tea Powder<br>
 * Step 3 → Add Sugar<br>
 * Step 4 → Add Milk<br>
 * Step 5 → Serve Tea<br><br>
 *
 * Here we focus on the sequence of steps rather than
 * the objects involved.<br><br>
 *
 * ====================================================<br><br>
 *
 * 🔹 2. Functional Programming<br><br>
 *
 * Functional Programming is a paradigm where computation
 * is performed using mathematical functions.<br><br>
 *
 * The main focus is on:
 * "What result should be produced."<br><br>
 *
 * In Functional Programming:<br>
 * • Functions are treated as first-class citizens<br>
 * • Functions can be passed as arguments<br>
 * • Functions can return other functions<br>
 * • Data is usually immutable (cannot be modified)<br><br>
 *
 * Examples:<br>
 * • Haskell<br>
 * • Lisp<br>
 * • Scala<br>
 * • Functional features in Java<br><br>
 *
 * Real-Life Example:<br><br>
 *
 * Suppose we want to calculate total marks.
 * Functions transform data and produce a result.<br><br>
 *
 * ====================================================<br><br>
 *
 * 🔹 3. Object Oriented Programming (OOP)<br><br>
 *
 * Object Oriented Programming is a paradigm where
 * programs are organized around Objects rather than
 * just functions or procedures.<br><br>
 *
 * The main focus is on:
 * "Who performs the task and what data belongs to it."<br><br>
 *
 * OOP combines both:<br>
 * • Data (Properties)<br>
 * • Behavior (Methods)<br><br>
 *
 * into a single unit called an Object.<br><br>
 *
 * Examples:<br>
 * • Java<br>
 * • C++<br>
 * • C#<br>
 * • Python<br><br>
 *
 * ====================================================<br><br>
 *
 * 🔹 What is OOPs?<br><br>
 *
 * OOPs (Object Oriented Programming System) is a
 * programming paradigm where everything is represented
 * in the form of Objects.<br><br>
 *
 * Instead of focusing only on functions and logic,
 * OOP focuses on creating real-world entities called
 * Objects and defining their properties and behaviors.<br><br>
 *
 * Important Points:<br><br>
 *
 * • Everything is represented in the form of Objects.<br>
 * • Objects are instances of Classes.<br>
 * • A Class acts as a blueprint for creating Objects.<br>
 * • An Object is the actual real-world entity created
 * from that blueprint.<br><br>
 *
 * Example:<br><br>
 *
 * Blueprint → House Plan<br>
 * Object    → Actual House Built Using That Plan<br><br>
 *
 * Similarly:<br><br>
 *
 * Class  → User<br>
 * Object → John, Sam, Asif, etc.<br><br>
 *
 * ====================================================<br><br>
 *
 * 🔹 Four Main Principles of OOPs<br><br>
 * 1. Encapsulation<br>
 * 2. Abstraction<br>
 * 3. Inheritance<br>
 * 4. Polymorphism<br><br>
 *
 * These four principles form the foundation of
 * Object Oriented Programming.<br><br>
 *
 * ====================================================<br><br>
 *
 * 🔹 Why OOP Became Popular?<br><br>
 *
 * As software systems became larger and more complex,
 * procedural programming became difficult to manage.<br><br>
 *
 * OOP introduced Classes and Objects, making programs
 * easier to design, maintain, reuse, and scale.<br><br>
 *
 * This is why most modern enterprise applications,
 * Android applications, games, and large software
 * systems are built using Object Oriented Programming.
 */


